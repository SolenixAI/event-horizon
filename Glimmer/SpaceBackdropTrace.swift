    /// The width over height of the loop, as drawn in brand/orbit.svg.
    static let aspect: CGFloat = 2.2627

    /// Cumulative fraction of the loop's length at each point, plus the closing 1.
    static let arc: [CGFloat] = {
        let n = points.count
        var lengths: [CGFloat] = [0]
        for i in 0..<n {
            let a = points[i], b = points[(i + 1) % n]
            lengths.append(lengths[i] + hypot(b.x - a.x, b.y - a.y))
        }
        let total = lengths[n]
        return lengths.map { $0 / total }
    }()

    /// The loop's frame in a view of `size`: most of the width, centred on
    /// the view's middle.
    static func frame(in size: CGSize, widthShare: CGFloat, centerY: CGFloat) -> CGRect {
        let width = size.width * widthShare
        let height = width / aspect
        return CGRect(x: (size.width - width) / 2, y: size.height * centerY - height / 2,
                      width: width, height: height)
    }

    /// The point `fraction` of the way round the loop (wraps past 1).
    static func point(at fraction: CGFloat, in frame: CGRect) -> CGPoint {
        let t = fraction - floor(fraction)
        let n = points.count
        var lo = 0, hi = n - 1
        while lo < hi {
            let mid = (lo + hi + 1) / 2
            if arc[mid] <= t { lo = mid } else { hi = mid - 1 }
        }
        let a = points[lo], b = points[(lo + 1) % n]
        let span = arc[lo + 1] - arc[lo]
        let local = span > 0 ? (t - arc[lo]) / span : 0
        let u = a.x + (b.x - a.x) * local, v = a.y + (b.y - a.y) * local
        return CGPoint(x: frame.minX + u * frame.width, y: frame.minY + v * frame.height)
    }

    /// The loop as a path inside `frame`.
    static func path(in frame: CGRect) -> CGPath {
        let path = CGMutablePath()
        for (i, p) in points.enumerated() {
            let point = CGPoint(x: frame.minX + p.x * frame.width, y: frame.minY + p.y * frame.height)
            if i == 0 { path.move(to: point) } else { path.addLine(to: point) }
        }
        path.closeSubpath()
        return path
    }
